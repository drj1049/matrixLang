#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "codegen.h"

static const char *binop_fn(char op) {
    switch (op) {
        case '+': return "mat_add";
        case '-': return "mat_sub";
        default:  return "mat_mul";
    }
}

static const char *call_fn(const char *name) {
    if (strcmp(name, "add") == 0)       return "mat_add";
    if (strcmp(name, "subtract") == 0)  return "mat_sub";
    if (strcmp(name, "multiply") == 0)  return "mat_mul";
    if (strcmp(name, "transpose") == 0) return "mat_transpose";
    return "mat_inverse";
}

/* declare every variable and temp once at the top of main */
static void declare_names(const TACProgram *tac, FILE *out) {
    char (*seen)[TAC_NAME_MAX] = malloc((size_t)(tac->count + 1) * TAC_NAME_MAX);
    int n = 0;
    for (int i = 0; i < tac->count; i++) {
        const TACInstr *ins = &tac->instrs[i];
        if (ins->op == TAC_PRINT) continue;
        int dup = 0;
        for (int j = 0; j < n; j++) {
            if (strcmp(seen[j], ins->result) == 0) { dup = 1; break; }
        }
        if (!dup) {
            strcpy(seen[n++], ins->result);
            fprintf(out, "    Mat v_%s = {0};\n", ins->result);
        }
    }
    free(seen);
}

void codegen_c(const TACProgram *tac, FILE *out) {
    fprintf(out, "/* generated by the MatrixLang compiler */\n");
    fprintf(out, "#include \"matrt.h\"\n\n");
    fprintf(out, "int main(void) {\n");
    declare_names(tac, out);
    fprintf(out, "\n");

    for (int i = 0; i < tac->count; i++) {
        const TACInstr *ins = &tac->instrs[i];
        switch (ins->op) {
        case TAC_LOAD_MATRIX:
            fprintf(out, "    v_%s = mat_from(%d, %d, (double[]){",
                    ins->result, ins->rows, ins->cols);
            for (int r = 0; r < ins->rows; r++) {
                for (int c = 0; c < ins->cols; c++) {
                    if (r > 0 || c > 0) fprintf(out, ", ");
                    fprintf(out, "%.17g", ins->matrix_values[r][c]);
                }
            }
            fprintf(out, "});\n");
            break;

        case TAC_BINOP:
            fprintf(out, "    v_%s = %s(v_%s, v_%s);\n",
                    ins->result, binop_fn(ins->binop), ins->arg1, ins->arg2);
            break;

        case TAC_CALL: {
            const char *fn = call_fn(ins->func_name);
            int n = ins->call_arg_count;
            fprintf(out, "    v_%s = ", ins->result);
            if (strcmp(ins->func_name, "transpose") == 0 ||
                strcmp(ins->func_name, "inverse") == 0) {
                fprintf(out, "%s(v_%s);\n", fn, ins->call_args[0]);
                break;
            }
            for (int k = 1; k < n; k++) fprintf(out, "%s(", fn);
            fprintf(out, "v_%s", ins->call_args[0]);
            for (int k = 1; k < n; k++) fprintf(out, ", v_%s)", ins->call_args[k]);
            fprintf(out, ";\n");
            break;
        }

        case TAC_COPY:
            fprintf(out, "    v_%s = v_%s;\n", ins->result, ins->src);
            break;

        case TAC_PRINT:
            fprintf(out, "    mat_print(\"%s\", v_%s);\n", ins->src, ins->src);
            break;
        }
    }

    fprintf(out, "    return 0;\n}\n");
}